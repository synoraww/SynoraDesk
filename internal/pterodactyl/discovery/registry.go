// Stats returns counts of endpoints in various statuses
func (r *Registry) Stats() map[EndpointStatus]int {
	counts := make(map[EndpointStatus]int)
	for _, ep := range r.Endpoints {
		counts[ep.Status]++
	}
	return counts
}
