package discovery

// EndpointStatus defines the implementation and testing state of an API endpoint
type EndpointStatus string

const (
	StatusDiscovered         EndpointStatus = "DISCOVERED"
	StatusDocumented         EndpointStatus = "DOCUMENTED"
	StatusImplemented        EndpointStatus = "IMPLEMENTED"
	StatusTested             EndpointStatus = "TESTED"
	StatusUnsupported        EndpointStatus = "UNSUPPORTED"
	StatusPermissionRequired EndpointStatus = "PERMISSION_REQUIRED"
)

// EndpointInfo holds comprehensive reverse-engineered metadata for a Pterodactyl API endpoint
type EndpointInfo struct {
	Name              string         `json:"name"`
	Method            string         `json:"method"`
	Path              string         `json:"path"`
	Category          string         `json:"category"` // "Client", "Application", "Admin"
	Subcategory       string         `json:"subcategory"`
	AuthType          string         `json:"auth_type"` // "Client API Token", "Application API Token"
	Permissions       []string       `json:"permissions"`
	SupportedVersions string         `json:"supported_versions"` // "1.x", "2.x", "1.x, 2.x"
	RequestSchema     string         `json:"request_schema"`
	ResponseSchema    string         `json:"response_schema"`
	Status            EndpointStatus `json:"status"`
	SourceFile        string         `json:"source_file"`
	Notes             string         `json:"notes"`
}

// Registry contains all discovered Pterodactyl endpoints
type Registry struct {
	Endpoints []EndpointInfo `json:"endpoints"`
}

